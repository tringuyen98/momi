#!/usr/bin/env python3
"""Run the same domain assertions without Swift Testing when only CLT is installed."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
source = (root / 'MomiCore/Tests/MomiCoreTests/CoreTests.swift').read_text()
methods = re.findall(r'@Test func (\w+)\(\)( throws)?', source)
source = source.replace('import Testing\n', '').replace('@testable import MomiCore', 'import MomiCore').replace('struct CoreTests', '@MainActor struct CoreTests').replace('@Test ', '').replace('#expect(throws:', 'expectThrows(').replace('#expect(', 'expect(')
harness = '''
@MainActor enum Harness { static var count = 0 }
@MainActor func expect(_ condition: @autoclosure () -> Bool, file: StaticString = #filePath, line: UInt = #line) {
    precondition(condition(), "Check failed at \\(file):\\(line)")
    Harness.count += 1
}
@MainActor func expectThrows<T>(_ type: T.Type, file: StaticString = #filePath, line: UInt = #line, _ body: () throws -> Void) {
    do { try body() } catch {
        precondition(error is T, "Unexpected error type at \\(file):\\(line)")
        Harness.count += 1; return
    }
    preconditionFailure("Expected error at \\(file):\\(line)")
}
@main struct Runner {
    @MainActor static func main() throws {
        let tests = CoreTests()
'''
harness += '\n'.join(f'        {"try " if throws else ""}tests.{name}()\n        print("PASS {name}")' for name, throws in methods)
harness += '\n        print("Passed \\(Harness.count) assertions.")\n    }\n}\n'
out = root / 'MomiCore/Sources/MomiCoreChecks/main.swift'
out.parent.mkdir(exist_ok=True)
out.write_text('// Generated by scripts/generate_core_checks.py from CoreTests.swift.\n' + source + harness)
print(f'Generated command-line runner for {len(methods)} tests.')
